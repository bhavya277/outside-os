import logging
from typing import Optional
from ..models.quest import Quest, QuestConfig
from .ollama_adapter import OllamaAdapter
from .fallback_generator import generate_fallback_quest

logger = logging.getLogger(__name__)

UNSAFE_KEYWORDS = [
    "trespass", "climb fence", "private property", "restricted area",
    "electric", "railroad", "train track", "highway", "toxic",
    "poisonous mushroom", "eat wild", "hazard", "wild animal feed",
    "cliff edge", "sewer", "storm drain"
]

class QuestService:
    def __init__(self, ollama_adapter: Optional[OllamaAdapter] = None):
        self.ollama = ollama_adapter or OllamaAdapter()

    def validate_safety_input(self, config: QuestConfig):
        """Rejects unsafe or out-of-scope user configurations."""
        user_text = f"{config.environment} {config.accessibility_notes or ''} {' '.join(config.activity_preferences)}".lower()
        for kw in UNSAFE_KEYWORDS:
            if kw in user_text:
                raise ValueError(
                    f"Configuration contains potentially hazardous keywords ('{kw}'). "
                    "OUTSIDE//OS adheres to strict physical safety principles: no trespassing, "
                    "no hazardous waste, no dangerous terrain, and no disturbance of wildlife."
                )

    def generate(self, config: QuestConfig, prefer_offline: bool = False, model_override: Optional[str] = None) -> Quest:
        """Main quest generation entry point: tries Ollama -> validates -> falls back deterministically."""
        self.validate_safety_input(config)

        if prefer_offline:
            logger.info("Offline preference requested. Generating via offline field library.")
            return generate_fallback_quest(config)

        status = self.ollama.check_status()
        if not status.ollama_available or not status.model_ready:
            logger.info("Ollama is unavailable or model not pulled. Employing deterministic fallback.")
            return generate_fallback_quest(config)

        try:
            quest = self.ollama.generate_quest(config, model_name=model_override)
            logger.info(f"Successfully generated quest via local model: {quest.provenance}")
            return quest
        except Exception as e:
            logger.warning(f"Ollama generation failed or timed out: {e}. Gracefully activating fallback library.")
            fallback = generate_fallback_quest(config)
            fallback.suitability_reason += " (Note: Generated by local fallback engine because Ollama inference was unavailable or timed out)."
            return fallback
